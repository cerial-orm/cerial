import { CerialGenerationError } from '../../errors';
import { getVariantIdentity, resolveInheritance } from '../../resolver';
import type { ASTField, ASTLiteralVariant, SchemaAST } from '../../types';

/** First line of the module; its presence is how a later run knows the file is its own to replace or remove. */
export const HANDLES_MARKER = '// Generated by Cerial from the .cerial declarations. Do not edit.';

// A declaration becomes `export const <Name>`, so a name the language reserves, or the import's own, cannot be one
const UNUSABLE_EXPORT_NAMES = new Set([
  'handle',
  'await',
  'break',
  'case',
  'catch',
  'class',
  'const',
  'continue',
  'debugger',
  'default',
  'delete',
  'do',
  'else',
  'enum',
  'export',
  'extends',
  'false',
  'finally',
  'for',
  'function',
  'if',
  'implements',
  'import',
  'in',
  'instanceof',
  'interface',
  'let',
  'new',
  'null',
  'package',
  'private',
  'protected',
  'public',
  'return',
  'static',
  'super',
  'switch',
  'this',
  'throw',
  'true',
  'try',
  'typeof',
  'var',
  'void',
  'while',
  'with',
  'yield',
]);

const text = (value: string): string => JSON.stringify(value);
const list = (values: readonly string[]): string => `[${values.map(text).join(', ')}]`;
const byName = <T extends { name: string }>(a: T, b: T): number => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

function exportLine(name: string, call: string): string {
  if (UNUSABLE_EXPORT_NAMES.has(name)) {
    throw new CerialGenerationError(
      `Declaration '${name}' cannot be exported from cerial/handles.ts because '${name}' is a reserved word. Rename it.`,
    );
  }

  return `export const ${name} = ${call};`;
}

/** `{ members, private, ... }` as the text `handle.*` takes; the private list is left out when empty */
function spec(members: readonly string[], hidden: readonly string[], extra: readonly string[] = []): string {
  const parts = [`members: ${list(members)}`, ...(hidden.length ? [`private: ${list(hidden)}`] : []), ...extra];

  return `{ ${parts.join(', ')} }`;
}

/** `Record(...)` id types of the `@id` field; `undefined` when the model has no `@id` field */
function idTypes(fields: readonly ASTField[]): readonly string[] | undefined {
  const id = fields.find((f) => f.decorators.some((d) => d.type === 'id'));

  return id ? (id.recordIdTypes ?? []) : undefined;
}

/** Variants unique by identity, in order; an extends merge already dedupes, a direct declaration may not */
function variantIdentities(variants: readonly ASTLiteralVariant[]): string[] {
  return [...new Set(variants.map(getVariantIdentity))];
}

/** The names `emitHandles` exports for `ast`, which are the names a schema module may import from the handles. */
export function handleExportNames(ast: SchemaAST): string[] {
  return [...ast.models, ...ast.objects, ...ast.tuples, ...ast.enums, ...ast.literals].map((d) => d.name).sort();
}

/**
 * The text of `cerial/handles.ts` for a pass-1 AST: one `handle.*` export per declaration, carrying member
 * names, `!!private` names, tuple size, literal simplicity and the `Record(...)` id types of a model.
 *
 * Members include what a declaration inherits, so a pick list naming an inherited field is valid. Inheritance is
 * resolved with the same resolver generation uses; privacy is read from the declaration's own raw fields,
 * because the resolver drops it and a child may omit but not redeclare a parent's private field.
 *
 * The result is deterministic (declarations sorted by name within kind) and is formatted by the writer.
 * The module imports only `cerial/schema`, never the generated client.
 */
export function emitHandles(ast: SchemaAST): string {
  const resolved = resolveInheritance(ast);
  const lines: string[] = [HANDLES_MARKER, '', "import { handle } from 'cerial/schema';", ''];

  const rawModels = new Map(ast.models.map((m) => [m.name, m]));
  for (const model of [...resolved.models].sort(byName)) {
    const members = model.fields.map((f) => f.name);
    const hidden = (rawModels.get(model.name)?.fields ?? []).filter((f) => f.isPrivate).map((f) => f.name);
    const ids = idTypes(model.fields);
    // The handle has no flag for abstract; the comment is the only record that it is not a table
    if (model.abstract) lines.push('// Abstract: declared in a .cerial file to be extended, never stored.');
    lines.push(
      exportLine(
        model.name,
        `handle.model(${text(model.name)}, ${spec(members, hidden, ids ? [`id: ${list(ids)}`] : [])})`,
      ),
    );
  }

  const rawObjects = new Map(ast.objects.map((o) => [o.name, o]));
  for (const object of [...resolved.objects].sort(byName)) {
    const hidden = (rawObjects.get(object.name)?.fields ?? []).filter((f) => f.isPrivate).map((f) => f.name);
    lines.push(
      exportLine(
        object.name,
        `handle.object(${text(object.name)}, ${spec(
          object.fields.map((f) => f.name),
          hidden,
        )})`,
      ),
    );
  }

  const rawTuples = new Map(ast.tuples.map((t) => [t.name, t]));
  for (const tuple of [...resolved.tuples].sort(byName)) {
    // An unnamed element has no member name; the handle reaches it by position up to `size`
    const members = tuple.elements.flatMap((e) => (e.name ? [e.name] : []));
    const hidden = (rawTuples.get(tuple.name)?.elements ?? []).flatMap((e) => (e.isPrivate && e.name ? [e.name] : []));
    lines.push(
      exportLine(
        tuple.name,
        `handle.tuple(${text(tuple.name)}, ${spec(members, hidden, [`size: ${tuple.elements.length}`])})`,
      ),
    );
  }

  for (const enumeration of [...resolved.enums].sort(byName)) {
    lines.push(exportLine(enumeration.name, `handle.enum(${text(enumeration.name)}, ${list(enumeration.values)})`));
  }

  for (const literal of [...resolved.literals].sort(byName)) {
    const simple = literal.variants.every(
      (v) => v.kind !== 'objectRef' && v.kind !== 'tupleRef' && v.kind !== 'literalRef',
    );
    lines.push(
      exportLine(
        literal.name,
        `handle.literal(${text(literal.name)}, { variants: ${list(variantIdentities(literal.variants))}, simple: ${simple} })`,
      ),
    );
  }

  return `${lines.join('\n')}\n`;
}
