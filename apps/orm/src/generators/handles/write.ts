import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, rmdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { CerialGenerationError } from '../../errors';
import type { SchemaAST } from '../../types';
import { formatCode } from '../shared';
import { emitHandles, HANDLES_MARKER } from './emit';

export type HandlesOutcome = 'written' | 'unchanged' | 'removed' | 'absent';

export function handlesPath(root: string): string {
  return join(root, 'cerial', 'handles.ts');
}

/**
 * Bring `<root>/cerial/handles.ts` in line with the entry. With `ast` (an entry mixing `.cerial` and
 * TypeScript) the file is written; with `null` a file this generator marked is removed. A file at the path
 * without the marker is the user's: writing over it is refused, and removing it never happens.
 */
export async function syncHandles(root: string, ast: SchemaAST | null): Promise<HandlesOutcome> {
  const path = handlesPath(root);
  const existing = existsSync(path) ? await readFile(path, 'utf-8') : undefined;
  const ours = existing?.startsWith(HANDLES_MARKER) ?? false;

  if (!ast) {
    if (existing === undefined || !ours) return 'absent';
    await rm(path);
    // The folder is only ours to tidy when nothing else lives there
    const dir = join(root, 'cerial');
    if (!(await readdir(dir)).length) await rmdir(dir);

    return 'removed';
  }

  if (existing !== undefined && !ours) {
    throw new CerialGenerationError(
      `${path} exists but was not generated by Cerial, so it was not overwritten. Move or delete it to generate handles.`,
    );
  }

  const content = await formatCode(emitHandles(ast), root);
  if (existing === content) return 'unchanged';
  await mkdir(join(root, 'cerial'), { recursive: true });
  await writeFile(path, content);

  return 'written';
}
