import { afterAll, describe, expect, it } from 'bun:test';
import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { handlesPath } from '../../../../src/generators/handles';
import { runPassOne } from '../../../../src/cli/passes';
import { removeTempProjects, tempProject } from '../../../registration-project';

afterAll(removeTempProjects);

const WHOLE = 'model Post {\n  id Record(int) @id\n  title String\n}\nobject Tag {\n  label String\n}\n';
// `Money` is declared in TypeScript, so the DSL-only parse cannot type the field
const TYPED_BY_TS = 'model Order {\n  id Record(int) @id\n  total Money\n}\n';

describe('runPassOne', () => {
  it('parses against .cerial names only and writes handles for what parsed whole', async () => {
    const root = await tempProject({});

    const ast = await runPassOne([{ path: 'a.cerial', content: WHOLE }], root);

    expect(ast.models.map((m) => m.name)).toEqual(['Post']);
    expect(ast.objects.map((o) => o.name)).toEqual(['Tag']);
    const text = await readFile(handlesPath(root), 'utf-8');
    expect(text).toContain('export const Post');
    expect(text).toContain('export const Tag');
  });

  it('resolves a type declared in another .cerial file', async () => {
    const root = await tempProject({});

    const ast = await runPassOne(
      [
        { path: 'a.cerial', content: 'model User {\n  id Record(int) @id\n  home Address\n}\n' },
        { path: 'b.cerial', content: 'object Address {\n  city String\n}\n' },
      ],
      root,
    );

    expect(ast.models[0]!.fields.map((f) => f.name)).toEqual(['id', 'home']);
  });

  it('leaves out a declaration whose field names a TypeScript-declared type, without reporting an error', async () => {
    const root = await tempProject({});

    const ast = await runPassOne(
      [
        { path: 'a.cerial', content: TYPED_BY_TS },
        { path: 'b.cerial', content: WHOLE },
      ],
      root,
    );

    expect(ast.models.map((m) => m.name)).toEqual(['Post']);
    expect(await readFile(handlesPath(root), 'utf-8')).not.toContain('export const Order');
  });

  it('refuses to overwrite a handles file the generator did not write', async () => {
    const root = await tempProject({ 'cerial/handles.ts': 'export const mine = 1;\n' });

    await expect(runPassOne([{ path: 'a.cerial', content: WHOLE }], root)).rejects.toThrow(
      'was not generated by Cerial',
    );
    expect(await readFile(handlesPath(root), 'utf-8')).toBe('export const mine = 1;\n');
  });

  it('rewrites its own file in place when the sources change', async () => {
    const root = await tempProject({});
    await runPassOne([{ path: 'a.cerial', content: WHOLE }], root);
    await writeFile(handlesPath(root), `${await readFile(handlesPath(root), 'utf-8')}\n// edited\n`);

    await runPassOne([{ path: 'a.cerial', content: WHOLE.replace('Post', 'Article') }], root);

    const text = await readFile(handlesPath(root), 'utf-8');
    expect(text).toContain('export const Article');
    expect(text).not.toContain('export const Post');
    expect(existsSync(handlesPath(root))).toBe(true);
  });
});
